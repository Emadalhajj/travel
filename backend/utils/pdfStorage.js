/*
=====================================================
PDF Storage Utility
=====================================================

ملف مساعد مسؤول عن تجهيز مجلدات حفظ ملفات PDF.

يستخدم في:
-----------------------------------------------------
- إنشاء مجلد uploads/vouchers إذا لم يكن موجودًا
- بناء رابط عام للملف يمكن إرساله للواجهة

الهدف:
-----------------------------------------------------
فصل منطق التخزين عن منطق إنشاء PDF.
=====================================================
*/

import fs from "fs";
import path from "path";

/*
=====================================================
ensurePdfFolderExists
=====================================================

تتأكد أن مجلد حفظ ملفات PDF موجود.

إذا لم يكن موجودًا:
-----------------------------------------------------
يتم إنشاؤه تلقائيًا.
 
مثال:
-----------------------------------------------------
uploads/vouchers
=====================================================
*/

export const ensurePdfFolderExists = (folderName = "vouchers") => {
  const folderPath = path.join(process.cwd(), "uploads", folderName);

  if (!fs.existsSync(folderPath)) {
    fs.mkdirSync(folderPath, { recursive: true });
  }

  return folderPath;
};

/*
=====================================================
buildPdfPublicPath
=====================================================

تبني الرابط العام للملف.

مثال:
-----------------------------------------------------
/uploads/vouchers/VCH-2026-123.pdf

هذا الرابط يتم حفظه في قاعدة البيانات.
=====================================================
*/

export const buildPdfPublicPath = (folderName, fileName) => {
  return `/uploads/${folderName}/${fileName}`;
};