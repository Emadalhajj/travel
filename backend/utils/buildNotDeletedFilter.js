// utils/buildNotDeletedFilter.js

/*
=====================================================
Build Not Deleted Filter Utility
=====================================================

هذا الملف مسؤول عن بناء فلتر عام لاستبعاد
العناصر المحذوفة حذفًا ناعمًا.

الفكرة:
-----------------------------------------------------
بدل أن نكرر هذا الشرط في كل query:

{
  isDeleted: false
}

نستخدم دالة موحدة.

يستخدم مع:
-----------------------------------------------------
- Booking
- DraftBooking
- Voucher
- Notification
- Inventory
- PaymentTransaction
- أي Model يحتوي على isDeleted

الهدف:
-----------------------------------------------------
توحيد فلترة البيانات غير المحذوفة.
=====================================================
*/

/*
=====================================================
buildNotDeletedFilter
=====================================================

تستقبل فلتر اختياري وتضيف له شرط isDeleted false.

مثال:
-----------------------------------------------------
buildNotDeletedFilter({ status: "pending" })

الناتج:
-----------------------------------------------------
{
  status: "pending",
  isDeleted: false
}
=====================================================
*/

export const buildNotDeletedFilter = (filter = {}) => {
  return {
    ...filter,
    isDeleted: false,
  };
};